// Alphabetisch für die Auswahl im Admin-Katalog.
export const ACHIEVEMENT_ICON_NAMES = Object.freeze(Object.keys(ICONS).sort());

function normalizeIconName(value) {
  return String(value || "")
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .toLowerCase();
}

export function AchievementIcon({ name, fallback = "circle", ...props }) {
  const Icon = ICONS[normalizeIconName(name)] || ICONS[normalizeIconName(fallback)] || Circle;
  return <Icon {...props} />;
}
